"""
Read-only loaders for curated public portfolio datasets.

The Streamlit application reads only the anonymised portfolio layer
generated by portfolio/generate_portfolio_data.py.

Production transaction data, model binaries, audit state, and raw
research evaluation populations are deliberately excluded.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]

PORTFOLIO_DATA_DIR = PROJECT_ROOT / "portfolio" / "data"

CUSTOMER_DECISIONS_PATH = (
    PORTFOLIO_DATA_DIR
    / "customer_decisions_portfolio.parquet"
)

REPEAT_PURCHASE_PATH = (
    PORTFOLIO_DATA_DIR
    / "repeat_purchase_portfolio.parquet"
)

DEMAND_FORECASTS_PATH = (
    PORTFOLIO_DATA_DIR
    / "demand_forecasts_portfolio.parquet"
)

MODEL_REGISTRY_PATH = (
    PORTFOLIO_DATA_DIR
    / "model_registry_portfolio.json"
)

PORTFOLIO_SUMMARY_PATH = (
    PORTFOLIO_DATA_DIR
    / "portfolio_summary.json"
)


REQUIRED_PORTFOLIO_FILES = (
    CUSTOMER_DECISIONS_PATH,
    REPEAT_PURCHASE_PATH,
    DEMAND_FORECASTS_PATH,
    MODEL_REGISTRY_PATH,
    PORTFOLIO_SUMMARY_PATH,
)


def validate_portfolio_data_files() -> None:
    """
    Fail closed if any required curated portfolio artifact is missing.
    """

    missing = [
        path
        for path in REQUIRED_PORTFOLIO_FILES
        if not path.is_file()
    ]

    if missing:
        formatted = ", ".join(
            str(path)
            for path in missing
        )

        raise FileNotFoundError(
            "Required portfolio data files are missing: "
            f"{formatted}"
        )


def _read_json(
    path: Path,
) -> dict[str, Any]:
    """
    Load and validate one JSON object.
    """

    if not path.is_file():
        raise FileNotFoundError(
            f"Portfolio JSON file does not exist: {path}"
        )

    with path.open(
        "r",
        encoding="utf-8",
    ) as handle:
        payload = json.load(
            handle
        )

    if not isinstance(
        payload,
        dict,
    ):
        raise RuntimeError(
            f"Portfolio JSON must contain an object: {path}"
        )

    return payload


def load_customer_decisions() -> pd.DataFrame:
    """
    Load anonymised customer decision outcomes.
    """

    validate_portfolio_data_files()

    frame = pd.read_parquet(
        CUSTOMER_DECISIONS_PATH
    )

    forbidden = {
        "customer",
        "recommended_product",
        "repeat_top1_product",
        "discovery_top1_product",
    }

    leaked = forbidden.intersection(
        frame.columns
    )

    if leaked:
        raise RuntimeError(
            "Raw identifiers found in public customer portfolio data: "
            f"{sorted(leaked)}"
        )

    required = {
        "portfolio_customer_id",
        "decision_date",
        "customer_state",
        "primary_action",
        "priority_tier",
        "contact_intensity",
        "experiment_requirement",
    }

    missing = (
        required
        -
        set(
            frame.columns
        )
    )

    if missing:
        raise RuntimeError(
            "Customer portfolio schema is incomplete: "
            f"{sorted(missing)}"
        )

    return frame


def load_repeat_purchase() -> pd.DataFrame:
    """
    Load anonymised Repeat Purchase scores.
    """

    validate_portfolio_data_files()

    frame = pd.read_parquet(
        REPEAT_PURCHASE_PATH
    )

    forbidden = {
        "customer",
        "first_invoice",
    }

    leaked = forbidden.intersection(
        frame.columns
    )

    if leaked:
        raise RuntimeError(
            "Raw identifiers found in public Repeat Purchase data: "
            f"{sorted(leaked)}"
        )

    return frame


def load_demand_forecasts() -> pd.DataFrame:
    """
    Load aggregate governed demand forecasts.
    """

    validate_portfolio_data_files()

    frame = pd.read_parquet(
        DEMAND_FORECASTS_PATH
    )

    if frame[
        "horizon_weeks"
    ].duplicated().any():
        raise RuntimeError(
            "Demand portfolio data contains duplicate horizons."
        )

    return (
        frame
        .sort_values(
            "horizon_weeks"
        )
        .reset_index(
            drop=True
        )
    )


def load_model_registry() -> dict[str, Any]:
    """
    Load the six-system public model register.
    """

    payload = _read_json(
        MODEL_REGISTRY_PATH
    )

    if payload.get(
        "system_count"
    ) != 6:
        raise RuntimeError(
            "Portfolio model registry must contain six systems."
        )

    systems = payload.get(
        "systems"
    )

    if not isinstance(
        systems,
        list,
    ) or len(
        systems
    ) != 6:
        raise RuntimeError(
            "Portfolio model registry systems are invalid."
        )

    return payload


def load_portfolio_summary() -> dict[str, Any]:
    """
    Load verified portfolio proof points.
    """

    payload = _read_json(
        PORTFOLIO_SUMMARY_PATH
    )

    evidence = payload.get(
        "verified_evidence"
    )

    if not isinstance(
        evidence,
        dict,
    ):
        raise RuntimeError(
            "Portfolio summary is missing verified evidence."
        )

    return payload


def load_portfolio_bundle() -> dict[str, Any]:
    """
    Load the complete curated application bundle.
    """

    return {
        "customer_decisions":
            load_customer_decisions(),

        "repeat_purchase":
            load_repeat_purchase(),

        "demand_forecasts":
            load_demand_forecasts(),

        "model_registry":
            load_model_registry(),

        "summary":
            load_portfolio_summary(),
    }